#!/usr/bin/env bash
# PostToolUse hook (Edit|Write|MultiEdit): format the touched C#/MSBuild file with the
# repo's pinned CSharpier (.config/dotnet-tools.json), exactly like build_local.sh does.
# Exit 2 = show stderr to Claude (e.g. the edit left a syntax error CSharpier can't parse).

set -uo pipefail

INPUT="$(cat)"
if command -v jq >/dev/null 2>&1; then
  FILE="$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty')"
else
  FILE="$(printf '%s' "$INPUT" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("file_path",""))')"
fi

[ -z "$FILE" ] && exit 0
[ -f "$FILE" ] || exit 0

case "$FILE" in
  *.cs|*.csproj|*.props|*.targets) ;;
  *) exit 0 ;;
esac

# Generated files carry an <auto-generated> header and CSharpier skips them anyway;
# submodules are excluded by .csharpierignore. Skip both early to save a dotnet start-up.
case "$FILE" in
  */protocol/*|*/rust-sdks/*|*/proto/*|*.g.cs) exit 0 ;;
esac

ROOT="${CLAUDE_PROJECT_DIR:-$(pwd)}"
cd "$ROOT" || exit 0

if ! OUT="$(dotnet csharpier format "$FILE" 2>&1)"; then
  if printf '%s' "$OUT" | grep -qiE "could not execute|not found|dotnet tool restore"; then
    echo "CSharpier is not available: run 'dotnet tool restore' in the repo root." >&2
    exit 1   # non-blocking: shown in the transcript, Claude carries on
  fi
  echo "CSharpier failed on $FILE (the edit probably left invalid syntax):" >&2
  printf '%s\n' "$OUT" >&2
  exit 2
fi

exit 0
