#!/usr/bin/env bash
# PreToolUse hook (Edit|Write|MultiEdit): block direct edits to generated code,
# vendored submodules and native binaries. Exit 2 = block and show stderr to Claude.
#
# Generators (./generate_proto.sh, LivekitRtc/download_ffi.sh) run through the Bash
# tool, so they are NOT affected by this hook.

set -uo pipefail

INPUT="$(cat)"
json_get() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$INPUT" | jq -r "$1 // empty"
  else
    printf '%s' "$INPUT" | python3 -c '
import json, sys
d = json.load(sys.stdin)
for k in sys.argv[1].lstrip(".").split("."):
    d = d.get(k) if isinstance(d, dict) else None
print(d or "")' "$1"
  fi
}

FILE="$(json_get '.tool_input.file_path')"
[ -z "$FILE" ] && exit 0

ROOT="${CLAUDE_PROJECT_DIR:-$(pwd)}"
REL="${FILE#"$ROOT"/}"
REL="${REL#./}"

block() {
  echo "BLOCKED: $REL is $1" >&2
  echo "Instead: $2" >&2
  exit 2
}

case "$REL" in
  LivekitApi/proto/*)
    block "generated by ./generate_proto.sh from the livekit/protocol submodule." \
      "change generate_proto.sh (proto list, sed patches) or bump the protocol submodule, then re-run ./generate_proto.sh. Hand-written behaviour goes in LivekitApi/*ServiceClient.cs." ;;
  LivekitRtc/Proto/*.g.cs)
    block "generated by ./generate_proto.sh from LivekitRtc/rust-sdks/livekit-ffi/protocol." \
      "bump the rust-sdks submodule and re-run ./generate_proto.sh. Mapping code goes in LivekitRtc/*.cs." ;;
  LivekitRtc/runtimes/*)
    block "a prebuilt native FFI library." \
      "run LivekitRtc/download_ffi.sh <livekit-ffi/vX.Y.Z> with the SAME version the rust-sdks submodule is checked out at." ;;
  protocol/*|LivekitRtc/rust-sdks/*)
    block "inside a vendored upstream git submodule." \
      "never patch upstream here. Check out a different upstream tag/commit, or work around it in this repo's own code." ;;
esac

exit 0
